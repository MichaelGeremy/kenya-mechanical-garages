def match_exact_car_models(
    budget_kes,
    primary_usage,
    ground_clearance_pref,
    body_style_pref,
    fuel_pref,
    spares_priority,
):
    """
    Intelligent car matchmaker that scores each of the 50 models
    based on the client's exact requirements and constraints in Kenya.
    """
    scored = []

    for car in CAR_MODELS:
        score = 50.0  # Base score

        # 1. Budget Fit
        car_min = car["price_min_kes"]
        car_max = car["price_max_kes"]
        
        if budget_kes <= 1200000:
            # Under 1.2M
            if car_min <= 1200000:
                score += 35
            elif car_min <= 1500000:
                score += 10
            else:
                score -= 40
        elif budget_kes <= 2000000:
            # 1.2M - 2.0M
            if car_min <= 2000000 and car_max >= 1200000:
                score += 35
            elif car_min <= 2400000:
                score += 15
            else:
                score -= 30
        elif budget_kes <= 3500000:
            # 2.0M - 3.5M
            if car_min <= 3500000 and car_max >= 1800000:
                score += 35
            elif car_min <= 4200000:
                score += 15
            else:
                score -= 20
        elif budget_kes <= 6000000:
            # 3.5M - 6.0M
            if car_min <= 6000000 and car_max >= 3000000:
                score += 35
            elif car_min <= 7500000:
                score += 15
        else:
            # Above 6.0M (High End)
            if car_max >= 5000000:
                score += 35

        # 2. Primary Usage Fit
        if primary_usage == "Daily Nairobi City Commute":
            if car["body_type"] in ["Hatchback", "Sedan"]:
                score += 25
            elif car["body_type"] in ["Crossover / SUV"]:
                score += 15
            elif car["body_type"] in ["Full-size 4x4", "Pickup"]:
                score -= 15
        elif primary_usage == "Family Upcountry & Weekend Trips":
            if car["body_type"] in ["Crossover / SUV", "Station Wagon", "Van / MPV"]:
                score += 30
            elif car["ground_clearance_mm"] >= 180:
                score += 15
        elif primary_usage == "Rough Rural Roads, Farm & Offroad":
            if car["ground_clearance_mm"] >= 200:
                score += 35
            if car["drivetrain"] in ["4WD", "AWD", "Part-time 4WD with Low Range", "Full-time 4WD", "Symmetrical AWD"]:
                score += 20
            if car["body_type"] in ["Hatchback", "Sedan"]:
                score -= 35
        elif primary_usage == "Executive Business & Highway Status":
            if car["brand"] in ["Mercedes-Benz", "BMW", "Toyota", "Land Rover / Range Rover", "Volkswagen / Audi"]:
                score += 30
            if car["body_type"] in ["Sedan", "Full-size 4x4", "Crossover / SUV"]:
                score += 15
            if car["brand"] in ["Suzuki", "Nissan"]:
                score -= 15
        elif primary_usage == "Business Logistics / Heavy Load Carry":
            if car["body_type"] in ["Pickup", "Pickup / Commercial", "Station Wagon"]:
                score += 40
            if car["model"] in ["Toyota Probox / Succeed", "Isuzu D-Max", "Toyota Hilux", "Isuzu N-Series (NMR / NPR)"]:
                score += 30

        # 3. Ground Clearance Preference
        if ground_clearance_pref == "Must be High (190 mm+ for bumps & rough roads)":
            if car["ground_clearance_mm"] >= 190:
                score += 25
            else:
                score -= 30
        elif ground_clearance_pref == "Standard (160 - 185 mm is fine for city & highway)":
            if car["ground_clearance_mm"] >= 155:
                score += 15

        # 4. Body Style Fit
        if body_style_pref != "Any Body Style":
            if car["body_type"] == body_style_pref:
                score += 30
            else:
                score -= 20

        # 5. Fuel Preference Fit
        if fuel_pref != "Any Fuel Type":
            if fuel_pref.lower() in car["fuel_type"].lower():
                score += 25
            else:
                score -= 20

        # 6. Spares Priority
        if spares_priority == "Maximum (Must find parts in every Kenyan town same day)":
            if car["parts_score"] >= 90:
                score += 30
            elif car["parts_score"] < 75:
                score -= 35
        elif spares_priority == "Balanced (Nairobi/Mombasa stock is fine, 1-2 days wait ok)":
            if car["parts_score"] >= 75:
                score += 15

        # Clamp between 25 and 99
        final_score = int(max(25, min(99, score)))
        scored.append((car, final_score))

    # Sort descending by match score
    scored.sort(key=lambda x: x[1], reverse=True)
    return scored
